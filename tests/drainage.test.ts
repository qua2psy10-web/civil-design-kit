import assert from 'node:assert/strict';
import { calculateDrainage as calculate, drainageExample as example } from '../lib/drainage.ts';
const close = (actual: number, expected: number) => assert.ok(Math.abs(actual - expected) < 1e-10);
const rectangle = calculate(example);
assert.ok(rectangle.values);
close(rectangle.values.designFlow, 64 / 360);
close(rectangle.values.area, .24);
close(rectangle.values.perimeter, 1.4);
close(rectangle.values.capacity, .24 / .013 * (.24 / 1.4) ** (2 / 3) * Math.sqrt(.005));
const half = calculate({ ...example, shape: 'circle', depth: .3 });
assert.ok(half.values);
close(half.values.area, Math.PI * .6 ** 2 / 8);
close(half.values.perimeter, Math.PI * .6 / 2);
close(half.values.radius, .6 / 4);
assert.equal(calculate({ ...example, depth: .6 }).values, null);
assert.equal(calculate({ ...example, slope: 0 }).values, null);
assert.equal(calculate({ ...example, coefficient: 1.1 }).values, null);
assert.equal(calculate({ ...example, rainfall: NaN }).values, null);
assert.equal(calculate({ ...example, catchment: 100 }).checks[0].ok, false);
assert.equal(calculate({ ...example, freeboard: .3 }).checks[1].ok, false);
assert.equal(calculate({ ...example, roughness: .1 }).checks[2].ok, false);
assert.equal(calculate({ ...example, slope: .5 }).checks[3].ok, false);
assert.ok(calculate({ ...example, diameter: NaN }).values);
console.log('PASS: rational units, rectangular flow, half-circle geometry, constraints and four NG states');
